"""Generate firmware pins and validation bounds from the PC's single profile."""
from pathlib import Path
import argparse
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "pc"))
from hand_can import DEFAULT_PROFILE, load_profile, profile_hash

OUTPUT = ROOT / "firmware" / "DexHandCan" / "BoardConfig.h"


def render(profile):
    motors = profile["motors"]
    def array(key):
        return ", ".join(str(m[key]) for m in motors)
    low = ", ".join(str(min(m["open_us"], m["close_us"])) for m in motors)
    high = ", ".join(str(max(m["open_us"], m["close_us"])) for m in motors)
    return f'''// Generated by tools/generate_board_config.py. Edit the JSON profile, not this file.
#pragma once
#include <stdint.h>
namespace hand_config {{
constexpr uint8_t kNodeId = {profile["device_id"]};
constexpr int kCanTx = {profile["can"]["tx_gpio"]};
constexpr int kCanRx = {profile["can"]["rx_gpio"]};
constexpr uint32_t kWatchdogMs = {profile["watchdog_ms"]};
constexpr uint32_t kAssemblyTimeoutMs = {profile["assembly_timeout_ms"]};
constexpr uint8_t kPins[15] = {{{array("gpio")}}};
constexpr uint16_t kMinUs[15] = {{{low}}};
constexpr uint16_t kMaxUs[15] = {{{high}}};
constexpr uint16_t kOpenUs[15] = {{{array("open_us")}}};
constexpr uint16_t kCloseUs[15] = {{{array("close_us")}}};
constexpr char kProfileSha256[] = "{profile_hash(profile)}";
}}  // namespace hand_config
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--profile", type=Path, default=DEFAULT_PROFILE)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    profile = load_profile(args.profile)
    if profile.get("hand") != "left" and args.output.resolve() == OUTPUT.resolve():
        parser.error("The default header belongs to the left template. Use prepare_firmware.py for separate left/right sketches, or set --output explicitly.")
    content = render(profile)
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != content:
            raise SystemExit("BoardConfig.h differs from the selected profile. Run the generator.")
        print("PASS: BoardConfig.h matches the selected profile")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(content, encoding="utf-8", newline="\n")
        print(args.output)


if __name__ == "__main__":
    main()

